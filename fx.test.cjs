const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const html = fs.readFileSync(`${__dirname}/index.html`, 'utf8');
const context = vm.createContext({state:{cash:1000,rows:[{code:'hk09992',cost:100,qty:10}],txs:[]},quotes:{hk09992:{price:120,prevClose:110,date:'2026-11-02'}},normalizeCode:x=>x});
vm.runInContext(html.slice(html.indexOf('function isTodayStockTrade('),html.indexOf('function renderAll()')),context);
context.loadSnapshots = () => [{date:'2026-10-30',stockValue:1000,cash:900,isClose:true}];
context.chinaDate = () => '2026-11-02';
assert.ok(Number.isNaN(context.calc().totalAsset));
vm.runInContext('hkdCny = 0.85',context);
assert.equal(context.calc().stockValue,1020);
assert.equal(context.calc().totalAsset,2020);
assert.equal(context.calc().totalPnl,170);
assert.equal(context.calc().todayPnl,85);
context.state.cash += 10000;
context.state.txs.push({type:'转入',amount:10000,time:'2026-11-02T09:00:00Z'});
assert.equal(context.calc().todayPnl,85);
context.state.cash -= 5000;
context.state.txs.push({type:'转出',amount:5000,time:'2026-11-02T10:00:00Z'});
assert.equal(context.calc().todayPnl,85);
assert.equal(context.assetDayPnl(2020, [], '2026-11-02'), null);
assert.equal(context.assetDayPnl(2020, [{date:'2026-10-30',stockValue:1000,cash:900}], '2026-11-02'), null);
console.log('PASS: RMB valuation, profit, daily profit, missing exchange rate');
const baseline=[{date:'2026-11-01',stockValue:80,cash:20,isClose:true}];
const transfer=(type,amount)=>({type,amount,time:'2026-11-02T02:00:00Z'});
assert.equal(context.assetDayPnl(150,baseline,'2026-11-02',[transfer('转入',50)]),0);
assert.equal(context.assetDayPnl(70,baseline,'2026-11-02',[transfer('转出',30)]),0);
assert.equal(context.assetDayPnl(130,baseline,'2026-11-02',[transfer('转入',50),transfer('转出',30)]),10);
assert.equal(context.assetDayPnl(110,baseline,'2026-11-02',[transfer('买入',50)]),10);
console.log('PASS: deposits, withdrawals and mixed cash flows excluded from PnL; trades untouched');
